(** The Collatz function. *)
let collatz k =
  if k mod 2 = 0 then k / 2 else 3 * k + 1

(** Should be raised if a Hailstone sequence is found to terminate,
    which is impossible. *)
exception HailstoneTerminates

(** The
    {{:https://en.wikipedia.org/wiki/Collatz_conjecture}Hailstone sequences}
    starting at [k] is generated by iterated application of [collatz k].
    It is unknown whether every Hailstone sequence contains [1],
    or how to compute whether one does. *)
module HailstoneSequence : Supply.WRITER
  with type elem = int
   and type init = int
= struct
  type elem = int
  type init = int

  (** The writer's internal state is the current entry in the sequence. *)
  type writer = int

  (** Construct a new writer. *)
  let make k = k

  (** Advance the sequence by emitting the current entry
      and computing the next one. *)
  let emit k = Supply.Data.Emit (k, collatz k)
end

(** This reader prints every integer it receives. *)
module PrintElems : Supply.READER
  with type elem = int
   and type init = unit
   and type output = unit
= struct
  type elem = int
  type init = unit

  (** The reader outputs no meaningful values. *)
  type output = unit

  (** The reader has no meaningful internal state. *)
  type reader = unit

  (** Construct a new reader. *)
  let make () = ()

  (** On receiving [n], print [n] and request to continue. *)
  let recv () n = Printf.printf "%d " n; Supply.Data.Continue ()
  
  (** Shutdown silently once the supply is empty. *)
  let shutdown () = ()
end

(** This reader processes integers until is encounters the value [1],
    at which point it outputs how many integers it processed
    before encountering [1]. *)
module ElemsUntilOne : Supply.READER
  with type elem = int
   and type init = unit
   and type output = int * bool
= struct
  type elem = int
  type init = unit

  (** The reader outputs [(m, b)] where
      - [m] is the number of elements the reader has processed,
      - and [b] is [true] iff the reader encountered a [1]. *)
  type output = int * bool

  (** The reader's internal state counts how many elements it has processed. *)
  type reader = int

  (** Construct a new reader. *)
  let make () = 0

  (** On receiving [n], either
      - output and shutdown if [n] is the value [1],
      - otherwise request to continue. *)
  let recv m n =
    match n with
    | 1 -> Supply.Data.Return (m, true)
    | _ -> Supply.Data.Continue (m + 1)

  (** Output and shutdown once the supply is empty. *)
  let shutdown m = (m, false)
end

(** Package a session interface in which the reader {!PrintElems}
    processes the Hailstone sequence writer {!HailstoneSequence}. *)
module PrintElemsOfHailstone = Supply.Run(struct
  type elem = int
  module Writer = HailstoneSequence
  module Reader = PrintElems
end)

(** Package a session interface in which the reader {!ElemsUntilOne}
    processes the Hailstone sequence writer {!HailstoneSequence}. *)
module ElemsUntilOneInHailstonre = Supply.Run(struct
  type elem = int
  module Writer = HailstoneSequence
  module Reader = ElemsUntilOne
end)

(** The Hailstone sequence starting at [k]. *)
let hailstone k =
  HailstoneSequence.make k

(** A time-bounded computation that, when allocated time [u],
    prints the first [u] elements of the Hailstone sequence starting at [k]. *)
let hailstone_printer k =
  PrintElemsOfHailstone.run (hailstone k) (PrintElems.make ())

(** A time-bounded computation that, when allocated time [u],
    searches [u] elements of the Hailstone sequence starting at [k]
    for the value [1]. *)
let hailstone_counter k =
  ElemsUntilOneInHailstonre.run (hailstone k) (ElemsUntilOne.make ())

(** Prints the first [n] elements of the Hailstone sequence starting at [k]. *)
let print_hailstone n k =
  Printf.printf "The first %d elements of `H%d` are: " n k;
  match Eventually.run (Timer.incr n Timer.zero) (hailstone_printer k) with
  | Timeout -> Printf.printf "...\n"
  | Success () -> raise HailstoneTerminates

(** Prints the number of steps until the Hailstone sequence starting at [k]
    reaches the value [1]. *)
let count_hailstone k =
  Printf.printf "Number of steps until `H%d` reaches one: " k;
  match Eventually.run Timer.forever (hailstone_counter k) with
  | Timeout -> raise Eventually.ForeverTimesout
  | Success (m, b) ->
    if b then Printf.printf "%d\n" m
    else raise HailstoneTerminates

(** Demonstrate the first [n] elements
    of the Hailstone sequence starting at [k]. *)
let demonstrate_hailstone n k =
  print_hailstone n k;
  count_hailstone k

(** Main executable.
    Demonstrate the Hailstone sequences starting at 6 and at 27. *)
let hailstone_main () =
  demonstrate_hailstone 15 6;
  print_endline "";
  demonstrate_hailstone 30 27
